// Pure guards for market-narrative story detection.
//
// scripts/build.mjs owns the Gemini call, the prompt, and the daily AI
// ceilings. This module only decides which previous names to show, when a
// thin extraction should be retried, and when a post-close carry is safe.
// No IO, no model calls, and no changes to the call/token caps.

/** Distinct real stories a fresh extraction should return. */
export const REAL_STORY_FLOOR = 4;
/** Source-pool headlines required before a thinner extraction is treated as a collapse. */
export const SOURCE_HEADLINE_FLOOR = 30;
/**
 * Newest-first history snapshots unioned into the previous-names list.
 * Five is the top of the 3–5 window: wide enough to see past a collapsed
 * latest snapshot, narrow enough that retired stories fall out.
 */
export const PREVIOUS_NAME_SNAPSHOTS = 5;

/** Shared prompt sentence. Replaces the old "reuse verbatim" instruction. */
export const PREVIOUS_NAME_REUSE_RULE =
  "reuse a name only if today's evidence still supports it, and cover every distinct story in today's news";

export function isRealNarrative(narrative) {
  if (!narrative || typeof narrative !== "object") return false;
  if (narrative.autogenerated) return false;
  const name = String(narrative.name || "").trim();
  if (!name || /\bwatchlist$/i.test(name)) return false;
  return true;
}

/** Distinct real story names, first spelling wins. Filler is dropped. */
export function realNarrativeNames(narratives) {
  const seen = new Set();
  const names = [];
  for (const row of Array.isArray(narratives) ? narratives : []) {
    if (!isRealNarrative(row)) continue;
    const name = String(row.name).trim();
    const key = name.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    names.push(name);
  }
  return names;
}

export function countRealNarratives(narratives) {
  return realNarrativeNames(narratives).length;
}

/**
 * Union of real names across the newest `snapshotCount` history snapshots.
 * History is newest-first. Dedup is case-insensitive and keeps the newest
 * spelling. Watchlist / autogenerated filler never enters the list.
 */
export function previousNarrativeNames(history, snapshotCount = PREVIOUS_NAME_SNAPSHOTS) {
  const limit = Math.max(0, Number(snapshotCount) || 0);
  const snaps = Array.isArray(history) ? history.slice(0, limit) : [];
  const seen = new Set();
  const names = [];
  for (const snap of snaps) {
    for (const name of realNarrativeNames(snap?.narratives)) {
      const key = name.toLowerCase();
      if (seen.has(key)) continue;
      seen.add(key);
      names.push(name);
    }
  }
  return names;
}

export function previousNamesPromptBlock(names) {
  const list = (Array.isArray(names) ? names : [])
    .map((name) => String(name || "").trim())
    .filter(Boolean);
  if (!list.length) return "No previous narratives recorded.";
  return `Previous narrative names from recent builds (${PREVIOUS_NAME_REUSE_RULE}):\n${list.map((name) => `- ${name}`).join("\n")}`;
}

/**
 * Citeable SOURCE POOL size. Macro lines follow the prompt cap. Ticker lines
 * are the first two headlines that have both a title and a publisher.
 * Sentiment is ignored: per-ticker calls that hit the AI cap stamp "unknown"
 * and must not hide a full headline pool.
 */
export function countNarrativeSourceHeadlines(chains, macroHeadlines, macroCap = 28) {
  const macros = Array.isArray(macroHeadlines) ? macroHeadlines : [];
  const cap = Number.isFinite(Number(macroCap)) ? Math.max(0, Number(macroCap)) : macros.length;
  let count = 0;
  for (const headline of macros.slice(0, cap)) {
    if (headline == null) continue;
    count += 1;
  }
  for (const data of Object.values(chains || {})) {
    const headlines = Array.isArray(data?.news?.headlines) ? data.news.headlines.slice(0, 2) : [];
    for (const headline of headlines) {
      if (!headline || typeof headline !== "object") continue;
      if (!headline.title || !headline.publisher) continue;
      count += 1;
    }
  }
  return count;
}

/**
 * True when one more reserved narrative call would still clear the hard
 * daily ceilings. This mirrors acquireAiSlot's priority path and does not
 * move those ceilings or consume a slot. The held-back reserve is exhausted
 * once a priority caller would be refused.
 */
export function narrativeReserveAvailable({
  tokensToday = 0,
  tokenCap = 0,
  recordedCalls = 0,
  reservedAttempts = 0,
  callCap = 0,
} = {}) {
  if (Number(tokenCap) > 0 && (Number(tokensToday) || 0) >= Number(tokenCap)) return false;
  const calls = Math.max(0, Number(recordedCalls) || 0) + Math.max(0, Number(reservedAttempts) || 0);
  if (Number(callCap) > 0 && calls >= Number(callCap)) return false;
  return true;
}

/**
 * Retry once when a fresh extraction is thin AND the source pool is large.
 * The trigger is headline count, never sentiment. An exhausted reserve skips
 * the retry instead of failing the build.
 */
export function collapsedStoryRetryDecision({
  realCount,
  headlineCount,
  reserveAvailable,
  realFloor = REAL_STORY_FLOOR,
  headlineFloor = SOURCE_HEADLINE_FLOOR,
} = {}) {
  const real = Number(realCount);
  const headlines = Number(headlineCount);
  const collapsed = Number.isFinite(real) && Number.isFinite(headlines)
    && real < realFloor
    && headlines >= headlineFloor;
  if (!collapsed) return { retry: false, reason: "ok" };
  if (!reserveAvailable) return { retry: false, reason: "reserve-exhausted" };
  return { retry: true, reason: "collapsed" };
}

/** Keep the extraction with more distinct real stories. A tie keeps the first. */
export function pickRicherNarrativeExtraction(first, retry) {
  const firstCount = countRealNarratives(first?.narratives);
  const retryCount = countRealNarratives(retry?.narratives);
  if (retryCount > firstCount) return { chosen: retry, source: "retry", realCount: retryCount };
  return { chosen: first, source: "first", realCount: firstCount };
}

/**
 * REFRESH_NARRATIVES=false may carry the prior extraction forward only when
 * it is present, unmarked stale, and still has a full real-story slate.
 */
export function refreshCarryDecision(lastGood, minReal = REAL_STORY_FLOOR) {
  const narratives = Array.isArray(lastGood?.narratives) ? lastGood.narratives : null;
  if (!narratives || narratives.length === 0) {
    return { carry: false, reason: "missing", realCount: 0 };
  }
  const realCount = countRealNarratives(narratives);
  if (narratives.some((row) => row?.stale === true)) {
    return { carry: false, reason: "stale", realCount };
  }
  if (realCount < minReal) return { carry: false, reason: "thin", realCount };
  return { carry: true, reason: "ok", realCount };
}
