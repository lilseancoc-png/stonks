// Mingstreet service worker (2026-11-06): lets the site open from the home
// screen with no connection, showing the last public copy it saw.
//
// What it keeps: the page shell (index.html with its inlined public manifest),
// app.js, styles.css, the js/ modules, the icons and the two public manifest
// sidecars. Every request is network first, so a connected visitor always gets
// the live site; the copy is only used when the network fails.
//
// What it never keeps: anything under /api/ (live quotes, sign-in, Owner
// routes) and every other /data/ file. Owner data is never written to the
// cache, so a shared device holds nothing private. Hand-written; not
// generated by the build. Bump VERSION to drop old copies.
const VERSION = "2026-11-06-1";
const CACHE = "mingstreet-shell-" + VERSION;
const PRECACHE = ["/", "/favicon.svg", "/manifest.webmanifest", "/icons/icon-192.png", "/icons/icon-512.png"];
const SHELL_PATH = /^\/(?:index\.html|app\.js|styles\.css|favicon\.svg|manifest\.webmanifest|js\/[\w./-]+\.js|icons\/[\w.-]+\.png)$/;
const PUBLIC_DATA = new Set(["manifest.json", "manifest-free.json"]);

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("mingstreet-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// The public manifest sidecars, however the page asks for them.
function publicDataKey(url) {
  if (url.pathname.startsWith("/data/")) return url.pathname.slice(6);
  if (url.pathname === "/api/auth/me" || url.pathname === "/api/data") return url.searchParams.get("data") || url.searchParams.get("key");
  return null;
}

// One copy per file: a new app.js?v=... replaces the old one.
async function keep(cacheKey, response) {
  const cache = await caches.open(CACHE);
  const path = new URL(cacheKey, self.location.origin).pathname;
  for (const req of await cache.keys()) {
    const u = new URL(req.url);
    if (u.pathname === path && req.url !== new URL(cacheKey, self.location.origin).href) await cache.delete(req);
  }
  await cache.put(cacheKey, response);
}

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  // Pages: the network, else the saved shell.
  if (req.mode === "navigate") {
    if (url.pathname !== "/" && url.pathname !== "/index.html") return;
    event.respondWith(
      fetch(req).then((res) => {
        if (res.ok && res.type === "basic" && !res.redirected) {
          const copy = res.clone();
          event.waitUntil(keep("/", copy));
        }
        return res;
      }).catch(async () => (await caches.match("/")) || Response.error()),
    );
    return;
  }

  const dataKey = publicDataKey(url);
  const isShell = SHELL_PATH.test(url.pathname);
  if (!isShell && !(dataKey && PUBLIC_DATA.has(dataKey))) return;
  // Public sidecars are stored under one key whichever route served them.
  const cacheKey = isShell ? req.url : "/__public-data/" + dataKey;
  event.respondWith(
    fetch(req).then((res) => {
      // Only plain public responses: never a private (no-store) answer.
      const cc = res.headers.get("Cache-Control") || "";
      if (res.ok && res.type === "basic" && !res.redirected && !/no-store|private/i.test(cc)) {
        const copy = res.clone();
        event.waitUntil(keep(cacheKey, copy));
      }
      return res;
    }).catch(async () => (await caches.match(cacheKey)) || Response.error()),
  );
});
