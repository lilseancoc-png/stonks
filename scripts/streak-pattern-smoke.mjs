import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {buildStreakMaContext} from '../lib/streak-ma-context.mjs';
import {PATTERN_HISTORY_DAYS, splitPatternHistory} from '../lib/pattern-history.mjs';
import {computeStreakForTicker, confirmedDailyBars, publicChainFilePayload, patternCloseSeries} from './build.mjs';
import {buildDivergenceStudy, buildPatternRecognition, buildLeadLag} from '../lib/pattern-recognition.mjs';
const bars = Array.from({length:206},(_,i)=>({t:new Date(Date.UTC(2025,0,i+1)).toISOString().slice(0,10),c:i===205?102:100,v:100}));
const ma = buildStreakMaContext(bars);
assert.deepEqual(ma.levels.map(m=>m.period),[20,50,100,200]);
assert.equal(ma.levels[0].value,100.1);
assert.equal(ma.levels[0].slope,'rising');
assert.equal(ma.levels[0].event,'reclaimed');
assert(ma.levels.every(m=>m.event==='reclaimed'));
assert.equal(buildStreakMaContext(bars.map((b,i)=>({...b,c:i===205?98:100}))).levels[0].event,'lost');
const row=computeStreakForTicker('TEST',bars);
assert.equal(row.maContext.levels.length,4,'MAs use the full bar series, beyond the 60-session streak window');
const live=confirmedDailyBars(bars,'REGULAR',new Date(bars.at(-1).t+'T16:00:00Z'));
assert(buildStreakMaContext(live).levels.every(m=>m.event===null),'unfinished close cannot reclaim an average');
assert.equal(buildStreakMaContext(bars.slice(-19)).levels.length,0);
assert(!buildStreakMaContext(bars.map((b,i)=>i===204?{...b,c:NaN}:b)).levels.length,'invalid prices never enter an MA');
const research=[];
for(let d=new Date('2024-10-28T12:00:00Z');d<=new Date('2026-10-27T12:00:00Z');d=new Date(+d+86400000)) if(d.getUTCDay()%6) research.push({t:d.toISOString().slice(0,10),c:100+research.length*.05+Math.sin(research.length/8),v:100});
const split=splitPatternHistory(research,new Date('2026-10-27T20:00:00Z'));
assert.equal(PATTERN_HISTORY_DAYS,730);
assert.equal(split.research.length,research.length);
assert(split.research.length>500 && split.technical.length<270);
assert.equal(split.technical[0].t,'2025-10-27');
const researchChain={_bars:split.technical,_patternBars:split.research,marketState:'CLOSED'};
assert.equal(patternCloseSeries(researchChain,'2026-10-27T21:00:00Z').length,split.research.length,'the production adapter uses the two-year series');
assert.equal(patternCloseSeries({...researchChain,marketState:'REGULAR'},'2026-10-27T15:00:00Z').at(-1).t,'2026-10-26','the production adapter excludes the live candle');
const peerBars=patternCloseSeries({_patternBars:split.research,marketState:'CLOSED'},'2026-10-27T21:00:00Z');
const peerStudy=buildLeadLag([{us:'TEST',peer:'PEER',sessionClass:'leading',usBars:patternCloseSeries(researchChain,'2026-10-27T21:00:00Z'),peerBars}]);
assert.equal(peerStudy.rows[0].n,split.research.length-1,'both sides of the peer study retain the older observations');
const publicData=publicChainFilePayload({_bars:split.technical,_patternBars:split.research,spot:100});
assert(!('_patternBars' in publicData));assert(!('_bars' in publicData));
const asSeries=b=>[{symbol:'TEST',closes:b.map(x=>x.c),dates:b.map(x=>x.t)}];
const longer=buildDivergenceStudy(asSeries(split.research)),shorter=buildDivergenceStudy(asSeries(split.technical));
assert(longer.baselineN>shorter.baselineN,'older observations reach the actual divergence study');
assert.equal(longer.record.rsiBearish.baselineAvgPct,-longer.record.rsiBullish.baselineAvgPct);
const payload=buildPatternRecognition({asOf:'2026-10-27',builtAtIso:'2026-10-27T21:00:00Z',divergences:asSeries(split.research)});
assert.equal(payload.history.stocks[0].firstDate,'2024-10-28');
assert.equal(payload.history.stocks[0].sessions,split.research.length);
assert.equal(payload.cost.extraYahooCharts,0);
const source=await readFile(new URL('./build.mjs',import.meta.url),'utf8');
assert.match(source,/const HISTORY_LOOKBACK_DAYS = PATTERN_HISTORY_DAYS/);
assert.match(source,/patternBars = history.research/);
assert.match(source,/const GLOBAL_HISTORY_DAYS = PATTERN_HISTORY_DAYS/);
console.log('Streak MA and two-year Pattern Lab checks passed: independent MA values, full-depth context, confirmed candles, scoring-window isolation, actual older observations, coverage, direction-matched benchmarks, and payload boundaries.');
