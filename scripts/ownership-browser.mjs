import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
import { createOwnershipPreview } from './ownership-preview.mjs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const preview = await createOwnershipPreview();
const output = process.env.OWNERSHIP_BROWSER_OUT || resolve(tmpdir(), 'stonks-ownership-browser');
await mkdir(output, { recursive: true });
let browser;
try {
  browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) });
  for (const width of [1440, 768, 390, 320]) for (const theme of ['dark', 'light']) {
    const context = await browser.newContext({ viewport: { width, height: 1000 }, acceptDownloads: true });
    const page = await context.newPage(), errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.addInitScript(t => localStorage.setItem('stonks-theme', t), theme);
    await page.route('**/*', route => new URL(route.request().url()).origin === preview.base ? route.continue() : route.fulfill({ body: '' }));
    await page.goto(preview.base + '/?tab=f13');
    const root = page.locator('#ownership-explorer-root'), search = page.locator('#own-search');
    try { await root.getByText('2 / 3 full books').waitFor({ timeout: 10000 }); }
    catch (error) { await page.screenshot({ path: resolve(output, 'failure.png'), fullPage: true }); console.error({ errors, text: (await page.locator('body').innerText()).slice(-6000) }); throw error; }
    await search.fill('ATLS');
    assert.match(await page.locator('#own-summary').innerText(), /6 matching disclosures across 2 funds/);
    assert.equal(await search.evaluate(el => el === document.activeElement), true, 'search keeps focus');
    await page.locator('#own-type').selectOption('stock');
    assert.match(await page.locator('#own-summary').innerText(), /2 matching disclosures/);
    assert.match(await page.locator('#own-results').innerText(), /125,000/);
    assert.match(await page.locator('#own-results').innerText(), /1,000/);
    await root.locator('.own-row-details').first().locator('summary').click();
    await root.locator('.own-row-details').first().getByText('Voting sole', { exact: true }).first().waitFor();
    assert.match(await page.locator('#own-results').innerText(), /Voting sole/);
    assert.match(await page.locator('#own-results').innerText(), /0000000001-26-000002/);
    await root.locator('.own-insiders summary').click();
    assert.match(await page.locator('#own-results').innerText(), /Test Insider/);
    assert.match(await root.locator('.own-insiders').innerText(), /\$0\.40/, 'insider prices retain cents');
    await page.locator('#own-sort').selectOption('aum');
    assert.match(await root.locator('.own-table tbody tr').first().innerText(), /Birch Partners/);
    await page.locator('#own-direction').selectOption('asc');
    assert.match(await root.locator('.own-table tbody tr').first().innerText(), /Atlas Capital/);
    await root.locator('[data-own-fund="Atlas Capital"]').first().click();
    assert.equal(await root.locator('[data-own-mode="funds"]').getAttribute('aria-pressed'), 'true');
    await search.fill('Small unchanged 89');
    assert.match(await page.locator('#own-summary').innerText(), /1 matching disclosures/);
    await root.locator('[data-own-clear]').click();
    await page.locator('#own-type').selectOption('all');
    assert.match(await page.locator('#own-page').innerText(), /Page 1 of 3/);
    await root.locator('[data-own-next]').click();
    assert.match(await page.locator('#own-page').innerText(), /Page 2 of 3/);
    const downloadPromise = page.waitForEvent('download');
    await root.locator('[data-own-download]').click();
    const download = await downloadPromise;
    const result = JSON.parse(await readFile(await download.path(), 'utf8'));
    assert.equal(result.results.length, 94, 'download covers every result, beyond visible page');
    assert(result.results.find(r => r.type === 'call').disclosures[0].votingSole === 900);
    await root.locator('[data-own-back]').click();
    await page.locator('#own-sort').selectOption('performancePct');
    await page.locator('#own-direction').selectOption('asc');
    assert.match(await root.locator('.own-table tbody tr').first().innerText(), /Birch Partners/);
    assert.match(await root.locator('.own-table tbody tr').last().innerText(), /Missing Manager/);
    await search.fill('Quant');
    assert.match(await page.locator('#own-summary').innerText(), /1 tracked funds/);
    await search.fill('nonexistent');
    assert.match(await page.locator('#own-results').innerText(), /No matches/);
    await root.locator('[data-own-clear]').click();
    await root.locator('[data-own-fund="Missing Manager"]').click();
    assert.match(await page.locator('#own-results').innerText(), /full holdings book is unavailable/);
    await root.locator('[data-own-mode="stocks"]').click();
    await search.fill('EXIT');
    await page.locator('#own-status').selectOption('exited');
    assert.match(await page.locator('#own-results').innerText(), /Exited Company/);
    await page.locator('#own-status').selectOption('held');
    await search.fill('ATLS');
    await root.screenshot({ path: resolve(output, 'ownership-' + width + '-' + theme + '.png') });
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
    assert.equal(overflow, false, 'tables scroll within the card at ' + width);
    assert.deepEqual(errors, []);
    await context.close();
  }
  const page = await browser.newPage();
  await page.route('**/*', route => new URL(route.request().url()).origin === preview.base ? route.continue() : route.fulfill({ body: '' }));
  preview.setMode('legacy'); await page.goto(preview.base + '/?tab=f13');
  await page.locator('#own-search').fill('ATLS');
  assert.match(await page.locator('#own-results').innerText(), /No matches/);
  assert.match(await page.locator('#ownership-explorer-root').innerText(), /0 \/ 1 full books/);
  preview.setMode('failure'); await page.reload();
  await page.getByText('Institutional filing data could not load').waitFor();
  preview.setMode('part-failure'); await page.reload();
  await page.getByText('Some collected book files could not load.', { exact: false }).waitFor();
  assert.match(await page.locator('#ownership-explorer-root').innerText(), /0 \/ 3 full books/);
  preview.setMode('full'); await page.locator('[data-f13-retry]').click();
  await page.locator('#ownership-explorer-root').getByText('2 / 3 full books').waitFor();
  preview.setMode('corrupt-part'); await page.reload();
  await page.getByText('Some collected book files could not load.', { exact: false }).waitFor();
  preview.setMode('full'); await page.locator('[data-f13-retry]').click();
  await page.locator('#ownership-explorer-root').getByText('2 / 3 full books').waitFor();
  preview.setMode('malformed'); await page.reload();
  await page.getByText('Institutional filing data could not load').waitFor();
  preview.setMode('full'); await page.locator('[data-f13-retry]').click();
  await page.locator('#ownership-explorer-root').getByText('2 / 3 full books').waitFor();
  await page.locator('#own-search').fill('ATLS');
  preview.setMode('source-failure');
  const details = page.locator('.own-row-details').first();
  await details.locator('summary').click();
  await details.getByText('Filed rows could not load.', { exact: false }).waitFor();
  preview.setMode('full');
  await details.locator('summary').click(); await details.locator('summary').click();
  await details.getByText('Voting sole', { exact: true }).first().waitFor();
  console.log('Ownership browser checks passed at desktop, tablet, 390px and 320px in light/dark themes, plus legacy and failed reads. Screenshots: ' + output);
} finally { await browser?.close(); await new Promise(r => preview.server.close(r)); }
