// Same attempt loop the narrative generator uses: a retryable failure burns one
// call per attempt and throws on the last. maxAttempts 1 therefore cannot spend
// the seven-attempt narrative budget.
function failingNarrativeGenerator({ maxAttempts }) {
  const limit = Math.max(1, Math.trunc(Number(maxAttempts)) || 7);
  let attempts = 0;
  for (let attempt = 0; attempt < limit; attempt++) {
    attempts += 1;
    if (attempt === limit - 1) {
      const err = new Error("narrative retry failed");
      err.attempts = attempts;
      err.maxAttempts = limit;
      throw err;
    }
  }
}

{
  const budget = narrativeRetryReserveInput();
  assert.equal(budget.briefMaxAttempts, 6);
  assert.equal(budget.briefTokenEstimate, 3072);
  assert.equal(budget.narrativeTokenEstimate, 32768);
  assert.equal(budget.reservedCalls, 30);
  assert.equal(budget.reservedTokens, 300_000);
  assert.ok(budget.callCap > budget.briefMaxAttempts + 1);
  assert.ok(budget.reservedTokens >= budget.briefTokenEstimate + budget.narrativeTokenEstimate);

  const callsNeeded = budget.briefMaxAttempts + 1;
  const tokensNeeded = budget.briefTokenEstimate + budget.narrativeTokenEstimate;
  const thin = { realCount: 1, headlineCount: SOURCE_HEADLINE_FLOOR };

  // Ledger two calls under the cap. A thin extraction over 30 headlines must
  // not run a seven-attempt retry: skip it, or spend exactly one call, and
  // leave at least one Brief slot.
  const capMinusTwo = narrativeRetryReserveInput({
    tokensToday: 1000,
    recordedCalls: budget.callCap - 2,
    reservedAttempts: 0,
  });
  const blocked = collapsedStoryRetryDecision({
    ...thin,
    reserveAvailable: narrativeReserveAvailable(capMinusTwo),
  });
  let attempts = 0;
  if (blocked.retry) {
    try {
      failingNarrativeGenerator({ maxAttempts: COLLAPSED_STORY_RETRY_ATTEMPTS });
    } catch (err) {
      attempts = err.attempts;
    }
  }
  const callsLeft = budget.callCap - (budget.callCap - 2) - attempts;
  assert.deepEqual(blocked, { retry: false, reason: "reserve-exhausted" });
  assert.equal(attempts, 0);
  assert.ok(callsLeft >= 1);
  let unbounded = 0;
  try { failingNarrativeGenerator({ maxAttempts: 7 }); } catch (err) { unbounded = err.attempts; }
  assert.equal(unbounded, 7);
  assert.ok(budget.callCap - (budget.callCap - 2) - unbounded < 1);

  // Exactly the Brief's attempts plus one narrative call still fits; one less does not.
  assert.equal(narrativeReserveAvailable(narrativeRetryReserveInput({
    tokensToday: 1000,
    recordedCalls: budget.callCap - callsNeeded,
    reservedAttempts: 0,
  })), true);
  assert.equal(narrativeReserveAvailable(narrativeRetryReserveInput({
    tokensToday: 1000,
    recordedCalls: budget.callCap - callsNeeded + 1,
    reservedAttempts: 0,
  })), false);

  // Tokens within one response of the ceiling skip the retry even when call slots remain.
  const tokenShort = collapsedStoryRetryDecision({
    ...thin,
    reserveAvailable: narrativeReserveAvailable(narrativeRetryReserveInput({
      tokensToday: budget.tokenCap - tokensNeeded + 1,
      recordedCalls: 10,
      reservedAttempts: 0,
    })),
  });
  assert.deepEqual(tokenShort, { retry: false, reason: "reserve-exhausted" });
  assert.equal(narrativeReserveAvailable(narrativeRetryReserveInput({
    tokensToday: budget.tokenCap - tokensNeeded,
    recordedCalls: 10,
    reservedAttempts: 0,
  })), true);
  // An intact reserve that is itself smaller than the Brief plus one narrative
  // response is not "near the cap", and still skips.
  assert.equal(narrativeReserveAvailable({
    tokensToday: 0,
    tokenCap: budget.tokenCap,
    recordedCalls: 0,
    reservedAttempts: 0,
    callCap: budget.callCap,
    reservedCalls: budget.reservedCalls,
    reservedTokens: tokensNeeded - 1,
    briefMaxAttempts: budget.briefMaxAttempts,
    briefTokenEstimate: budget.briefTokenEstimate,
    narrativeTokenEstimate: budget.narrativeTokenEstimate,
  }), false);

  // Open reserve: the retry runs, the generator is asked for one attempt, and
  // a failure stops there.
  const open = collapsedStoryRetryDecision({
    ...thin,
    reserveAvailable: narrativeReserveAvailable(narrativeRetryReserveInput({
      tokensToday: 1000,
      recordedCalls: 10,
      reservedAttempts: 0,
    })),
  });
  assert.deepEqual(open, { retry: true, reason: "collapsed" });
  let openAttempts = 0;
  let seenMaxAttempts = null;
  if (open.retry) {
    try {
      failingNarrativeGenerator({ maxAttempts: COLLAPSED_STORY_RETRY_ATTEMPTS });
    } catch (err) {
      openAttempts = err.attempts;
      seenMaxAttempts = err.maxAttempts;
    }
  }
  assert.equal(seenMaxAttempts, 1);
  assert.equal(openAttempts, 1);
  assert.ok(budget.callCap - 10 - openAttempts >= budget.briefMaxAttempts);
}

{
  const first = { narratives: [story("Only One"), filler("Banks Watchlist")] };
  const richer = { narratives: [story("Only One"), story("Rates"), story("Oil"), story("Dollar"), story("Gold")] };
  const same = { narratives: [story("Only One"), story("only one")] };
  assert.equal(pickRicherNarrativeExtraction(first, richer).source, "retry");
  assert.equal(pickRicherNarrativeExtraction(first, same).source, "first");
  assert.equal(countRealNarratives(first.narratives), 1);
  assert.equal(pickRicherNarrativeExtraction(richer, first).source, "first");
}

{
  const real = [story("A"), story("B"), story("C"), story("D")];
  const watchlists = [filler("Banks Watchlist"), story("Energy Watchlist")];
  assert.equal(refreshCarryDecision({ narratives: real }).carry, true);
  assert.equal(refreshCarryDecision({ narratives: real.concat(watchlists) }).reason, "ok");
  assert.deepEqual(
    refreshCarryDecision({ narratives: real.map((row) => ({ ...row, stale: true })) }),
    { carry: false, reason: "stale", realCount: 4 },
  );
  assert.equal(refreshCarryDecision({
    narratives: [story("A", { stale: true }), story("B"), story("C"), story("D")],
  }).reason, "stale");
  assert.deepEqual(
    refreshCarryDecision({ narratives: [story("A"), story("B"), story("C")].concat(watchlists) }),
    { carry: false, reason: "thin", realCount: 3 },
  );
  assert.equal(refreshCarryDecision({ narratives: [] }).reason, "missing");
  assert.equal(refreshCarryDecision(null).reason, "missing");
  assert.equal(refreshCarryDecision({ narratives: watchlists }).reason, "thin");
}

