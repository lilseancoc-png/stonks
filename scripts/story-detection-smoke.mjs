// Same walk as aiTokensToday / aiCallsToday, plus the summary's unguarded
// `calls += b.calls` so a non-bucket stuffed into dates[day] becomes NaN.
function ledgerSums(state, day) {
  const byDate = state?.dates?.[day];
  let tokens = 0;
  let calls = 0;
  let rawCalls = 0;
  if (!byDate) return { tokens, calls, rawCalls };
  for (const byModel of Object.values(byDate)) {
    for (const b of Object.values(byModel)) {
      tokens += (b.inputTokens || 0) + (b.outputTokens || 0) + (b.thoughtTokens || 0);
      calls += Number(b.calls) || 0;
      rawCalls += b.calls;
    }
  }
  return { tokens, calls, rawCalls };
}

// Bake order: cap check beside the reserve check, then count the start
// before the generator runs. A thrown generator leaves the count in place.
function runCollapsedRetry(state, day, { fail = false, reserveAvailable = true } = {}) {
  const decision = collapsedStoryRetryDecision({
    realCount: 1,
    headlineCount: SOURCE_HEADLINE_FLOOR,
    reserveAvailable,
    retryCapAvailable: collapsedRetryCapAllows(state, day),
  });
  if (!decision.retry) return { ...decision, started: false };
  recordCollapsedRetryStart(state, day);
  if (fail) throw new Error("narrative retry failed");
  return { ...decision, started: true };
}

{
  const day = "2026-10-13";
  const nextDay = "2026-10-14";
  const state = {
    dates: {
      [day]: {
        "gemini-3.6-flash": {
          narratives: { calls: 3, inputTokens: 1000, outputTokens: 40, cachedTokens: 9, thoughtTokens: 10 },
        },
      },
    },
  };
  assert.equal("retryCounters" in state, false);
  assert.equal(collapsedRetryCapAllows(state, day), true);
  assert.equal(collapsedRetryCapAllows(null, day), true);
  const datesBefore = JSON.parse(JSON.stringify(state.dates));
  const sumsBefore = ledgerSums(state, day);
  assert.deepEqual(sumsBefore, { tokens: 1050, calls: 3, rawCalls: 3 });

  for (let i = 0; i < COLLAPSED_STORY_RETRY_DAILY_CAP; i++) {
    let failed = false;
    try {
      runCollapsedRetry(state, day, { fail: true });
    } catch (err) {
      failed = true;
      assert.equal(err.message, "narrative retry failed");
    }
    assert.equal(failed, true);
    assert.equal(state.retryCounters[day], i + 1);
  }
  const third = runCollapsedRetry(state, day, { fail: true });
  assert.deepEqual(third, { retry: false, reason: "daily-cap", started: false });
  assert.equal(state.retryCounters[day], COLLAPSED_STORY_RETRY_DAILY_CAP);

  assert.equal(collapsedRetryCapAllows(state, nextDay), true);
  assert.deepEqual(runCollapsedRetry(state, nextDay), { retry: true, reason: "collapsed", started: true });
  assert.equal(state.retryCounters[nextDay], 1);
  assert.equal(state.retryCounters[day], COLLAPSED_STORY_RETRY_DAILY_CAP);

  assert.deepEqual(state.dates, datesBefore);
  assert.deepEqual(Object.keys(state.dates[day]), ["gemini-3.6-flash"]);
  assert.equal(state.dates[day].retryCounters, undefined);
  assert.deepEqual(ledgerSums(state, day), sumsBefore);
  assert.equal(Number.isNaN(ledgerSums(state, day).rawCalls), false);

  const saved = JSON.parse(JSON.stringify(state));
  assert.equal(saved.retryCounters[day], COLLAPSED_STORY_RETRY_DAILY_CAP);
  assert.equal(saved.retryCounters[nextDay], 1);
  assert.deepEqual(ledgerSums(saved, day), sumsBefore);

  state.retryCounters["2020-01-01"] = 2;
  state.retryCounters["2026-09-29"] = 1;
  pruneCollapsedRetryCounters(state, nextDay);
  assert.equal(state.retryCounters["2020-01-01"], undefined);
  assert.equal(state.retryCounters["2026-09-29"], undefined);
  assert.equal(state.retryCounters[day], undefined);
  assert.equal(state.retryCounters[nextDay], 1);
  assert.deepEqual(state.dates, datesBefore);
  assert.deepEqual(ledgerSums(state, day), sumsBefore);

  const bare = { dates: { [day]: { "gemini-3.6-flash": { narratives: { calls: 1, inputTokens: 1, outputTokens: 0, thoughtTokens: 0 } } } } };
  pruneCollapsedRetryCounters(bare, day);
  assert.equal(Object.prototype.hasOwnProperty.call(bare, "retryCounters"), false);
  assert.equal(ledgerSums(bare, day).calls, 1);

  const weird = { dates: { [day]: state.dates[day] }, retryCounters: [1, 2] };
  assert.equal(collapsedRetryCapAllows(weird, day), true);
  assert.equal(recordCollapsedRetryStart(weird, day), 1);
  assert.deepEqual(weird.retryCounters, { [day]: 1 });
  assert.deepEqual(weird.dates, datesBefore);
}

