import assert from 'node:assert/strict';
import vm from 'node:vm';
import { callReportContext, leveragedEntryPlan, earningsCallAge, pickDisplayDecision, shareEntryPayoff, pickReviewCheckpoint, scenarioEventPhase } from '../lib/research-display.mjs';

export function verifyResearchDisplay(appJs) {
  const tracker={builtAtIso:'2026-09-04T20:00:00Z',seasons:[{rows:[{sym:'LULU',date:'2026-09-03',epsActual:2}]}]};
  assert.equal(callReportContext({sym:'LULU',callDate:'2026-06-04'},tracker,Date.parse('2026-09-05')).newer,true);
  assert.match(callReportContext({sym:'LULU',callDate:'2026-09-03'},tracker,Date.parse('2026-09-05')).label,/Matches latest/);
  assert.match(callReportContext({sym:'LULU',callDate:'2026-09-03'},tracker,Date.parse('2026-09-15')).label,/not verified/);
  const lev = {etf:'ORCU',direction:'bull',leverage:2,under:{symbol:'ORCL',spot:157.31},entry:{state:'wait'},plan:{entry:{now:false,trigger:155.74},invalidation:{underlyingPx:141.77},target:{underlyingPx:180.62},riskReward:1.5}};
  const lp = leveragedEntryPlan(lev);
  assert.equal(lp.riskReward.toFixed(2),'1.78');
  assert.equal(lp.target.etfMovePct.toFixed(1),'32.0');
  const inverse = {...lev,direction:'bear',leverage:-2,plan:{entry:{trigger:100},invalidation:{underlyingPx:110},target:{underlyingPx:80}}};
  assert.equal(leveragedEntryPlan(inverse).riskReward,2);
  assert.equal(leveragedEntryPlan({...inverse,plan:{...inverse.plan,target:{underlyingPx:105}}}).riskReward,null);
  assert.equal(leveragedEntryPlan({...lev,plan:{...lev.plan,entry:{now:false,trigger:null}}}).riskReward,null);
  assert.equal(earningsCallAge({callDate:'2026-06-04'},Date.parse('2026-09-05')).recent,false);
  assert.equal(earningsCallAge({callDate:'2026-09-02'},Date.parse('2026-09-05')).recent,true);
  assert.equal(earningsCallAge({published:'2026-09-05'},Date.parse('2026-09-05')).age,null);
  assert.equal(earningsCallAge({callDate:'2026-10-01'},Date.parse('2026-09-05')).recent,false);
  const be = { symbol:'BE', group:'watch', entry:{now:false, headline:'Wait for reset',trigger:239.05}, contract:{expiry:Date.parse('2026-11-20T21:00:00Z')/1000}, entryPlan:{stance:'full',strategy:{name:'Full entry',blurb:'Full size OK'},tranches:[{label:'Enter now',price:251.63,size:'100%'}]} };
  assert.equal(pickDisplayDecision(be).ready, false);
  const ready = {...be,group:'actionable',entry:{now:true,headline:'Confirmed'}};
  assert.equal(pickDisplayDecision(ready).ready, true);
  for (const p of [{...ready,entryTiming:{hardWait:true}},{...ready,entryTiming:{hardVeto:true}},{...ready,strategy:{type:'none'}},{...ready,contract:null},{...ready,entry:{now:false}}]) assert.equal(pickDisplayDecision(p).ready,false);
  assert.equal(pickDisplayDecision({...ready,entryTiming:{state:'wait'},entry:{now:true,basis:'ai-final-grader'}}).ready,true);
  const gd = shareEntryPayoff({action:{key:'wait'},entry:{price:380.06},target:{price:377.91},review:{price:358.07}});
  assert.equal(gd.rr,null);
  assert.ok(gd.upsidePct < 0);
  assert.match(gd.warning,/at or below/);
  assert.equal(shareEntryPayoff({action:{key:'starter'},entry:{price:100},target:{price:120},review:{price:90}}).rr.toFixed(2),'2.00');
  assert.equal(shareEntryPayoff({action:{key:'research'},entry:{price:100},target:{price:120},review:{price:90}}).rr,null);
  assert.equal(shareEntryPayoff({entry:{price:null},target:{price:120},review:{price:90}}).rr,null);
  assert.equal(shareEntryPayoff({entry:{price:100},target:{price:120},review:{price:101}}).rr,null);
  assert.equal(pickReviewCheckpoint(be,Date.parse('2026-09-04')).date,'2026-11-06');
  assert.equal(pickReviewCheckpoint(be,Date.parse('2026-11-07')).due,true);
  assert.equal(pickReviewCheckpoint({contract:{}}),null);
  assert.equal(pickReviewCheckpoint(be,Date.parse('2026-11-21')).expired,true);
  const jobs = {date:'2026-09-04',window:'08:30 ET'};
  assert.equal(scenarioEventPhase(jobs,Date.parse('2026-09-04T12:29:00Z')),'upcoming');
  assert.equal(scenarioEventPhase(jobs,Date.parse('2026-09-04T12:30:00Z')),'past');
  assert.equal(scenarioEventPhase({date:'2026-09-04',window:'PM'},Date.parse('2026-09-05T01:00:00Z')),'today');
  assert.equal(scenarioEventPhase({date:'2026-09-05',window:'today'},Date.parse('2026-09-05T01:00:00Z')),'upcoming');
  assert.equal(scenarioEventPhase({date:'2026-12-04',window:'08:30 ET'},Date.parse('2026-12-04T13:00:00Z')),'upcoming');

  const section = (start,end) => appJs.slice(appJs.indexOf(start),appJs.indexOf(end,appJs.indexOf(start)));
  const context = {pickDisplayDecision,pickReviewCheckpoint,escapeHtml:x=>String(x),Date};
  vm.createContext(context);
  vm.runInContext(section('  function pickEntryPlanHtml(', '  function pickExitPlanHtml('),context);
  const heldHtml = context.pickEntryPlanHtml(be);
  assert.match(heldHtml,/Wait for confirmation/);
  assert.match(heldHtml,/239\.05/);
  assert.doesNotMatch(heldHtml,/Enter now|Full size OK|251\.63/);
  assert.match(context.pickEntryPlanHtml(ready),/Entry plan/);
  vm.runInContext(section('  function pickPlanSummaryHtml(', '  function buildPickCardHtml('),context);
  assert.match(context.pickPlanSummaryHtml(be),/Pre-expiration review/);
  assert.match(context.pickPlanSummaryHtml(be),/2026-11-06/);
  const live = {isFinite}; vm.createContext(live);
  vm.runInContext(section('  function liveEntryOverlay(', '  function applyLiveEntryChips('),live);
  assert.equal(live.liveEntryOverlay({...be,entry:{...be.entry,signal:'wait-pullback'}},230).kind,'arm');
  assert.match(appJs,/Includes watch ideas · not deployed/);
  assert.match(appJs,/modeled win rate · n=/);
  assert.match(appJs,/candidateBoard \+ modelRecord \+ researchContext/);
  const levCtx = {leveragedEntryPlan, escapeHtml:x=>String(x), fmt:(v,n)=>v==null?'—':Number(v).toFixed(n), fmtMoney:v=>'$'+Number(v).toFixed(2),formatDisplayInstant:s=>s,
    levState:{quotes:{},displayQuotes:{ORCU:{regularSpot:8.85,regularAsOf:'2026-09-04T20:00:00Z',marketState:'POST'}},data:{record:{open:[]}}}};
  vm.createContext(levCtx);
  vm.runInContext(section('  function levDecision(', '  function applyLevRiskSizing('),levCtx);
  assert.equal(levCtx.levDecision(lev),'wait');
  assert.equal(levCtx.levDecision({...lev,entry:{state:'avoid'}}),'pass');
  assert.equal(levCtx.levDecision({...lev,entry:{state:'go'},plan:{...lev.plan,entry:{now:true}}}),'now');
  const closeHtml = levCtx.levLiveLine(lev);
  assert.match(closeHtml,/8.85/); assert.match(closeHtml,/2026-09-04/); assert.doesNotMatch(closeHtml,/live quote/);
  vm.runInContext(section('  function levEarnChip(', '  function levPickChip('),levCtx);
  assert.match(levCtx.levEarnChip({leverage:2,earnings:{daysUntil:6,impliedMovePct:0.061}}),/6.1%/);
  vm.runInContext(section('  function levVisibleIdeas(', '  function levDeskHtml('),levCtx);
  const bad = {...inverse,etf:'BAD',plan:{...inverse.plan,target:{underlyingPx:101}}};
  levCtx.levState.setup='wait';levCtx.levState.direction='all';
  assert.equal(levCtx.levVisibleIdeas([lev,bad]).length,1);
  levCtx.levState.setup='pass';assert.equal(levCtx.levVisibleIdeas([lev,bad])[0].etf,'BAD');
  const flowCtx = {};vm.createContext(flowCtx);
  vm.runInContext(section('  function flowDecisionCandidate(', '  function flowGexContext('),flowCtx);
  const contract={side:'call',strike:100,tape:'ask',deltaPremium:120000,deltaVol:5000,repeatCount:2,bid:1,ask:1.1};
  const fs=flowCtx.flowDecisionStats([{symbol:'A',spot:100,contracts:[contract]},{symbol:'B',spot:100,contracts:[contract,contract]}]);
  assert.equal(fs.contracts,3);assert.equal(fs.top.contracts,2);assert.ok(fs.top.contracts<=fs.top.rawContracts);
  const focusHost={};
  Object.assign(flowCtx, {$:()=>focusHost, flowFreshnessMeta:()=>({executable:false,label:'Closed-session reference',detail:'Market closed'}),escapeHtml:x=>String(x),fmtBigDollars:x=>'$'+x,fmtDelta:x=>String(x),symGradeHref:x=>'?s='+x});
  vm.runInContext(section('  function flowGexContext(', '  function renderFlowSummary('),flowCtx);
  flowCtx.renderFlowDecision([{symbol:'A',spot:100,contracts:[contract]},{symbol:'B',spot:100,contracts:[contract,contract]}]);
  assert.match(focusHost.innerHTML,/2 qualified \/ 2 visible for B/);
  assert.match(focusHost.innerHTML,/Focus qualified premium/);
  assert.doesNotMatch(focusHost.innerHTML,/Actionable premium|3 qualified \/ 2/);
  assert.match(appJs,/top.contracts \+ ' qualified \/ '/);
  const cmpCtx={};vm.createContext(cmpCtx);
  vm.runInContext(section('  function cmpMetricRows(', '  function cmpIsNum('),cmpCtx);
  const rows=cmpCtx.cmpMetricRows(), row=k=>rows.find(r=>r.key===k);
  assert.equal(row('spot').deltaKind,'none');assert.equal(row('debtToEquity').fmt,'pct');
  assert.ok(Math.abs(row('drawdown52').get({spot:80,fundamentals:{fiftyTwoWeekHigh:100}})-20)<1e-9);
  assert.equal(row('fcfYield').get({fundamentals:{freeCashFlow:5,marketCap:100}}),5);
  assert.equal(row('drawdown52').get({spot:80,fundamentals:{}}),null);

}
