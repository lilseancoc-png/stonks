import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { createUnifiedSignalPreview } from './unified-signal-preview.mjs';
import { UNIFIED_FIXTURE_TIME } from './fixtures/unified-signal.mjs';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const preview=await createUnifiedSignalPreview();
const output=process.env.QA_OUTPUT||resolve(tmpdir(),'stonks-unified-browser');
await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{})});
let checks=0;
const check=(condition,label)=>{assert.ok(condition,label);checks++;};
try{
  const context=await browser.newContext({viewport:{width:1440,height:1050}});
  await context.route('**/*',route=>new URL(route.request().url()).origin===preview.base?route.continue():route.abort());
  const page=await context.newPage(),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.clock.install({time:new Date(UNIFIED_FIXTURE_TIME)});
  for(const [width,theme] of [[1440,'dark'],[1024,'light'],[390,'dark'],[390,'light'],[768,'dark'],[1440,'light']]){
    preview.setScenario('owner');
    await page.setViewportSize({width,height:1050});
    await page.addInitScript(value=>localStorage.setItem('stonks-theme',value),theme);
    await page.goto(preview.base+'/?tab=unified-signal-engine');
    const root=page.locator('#unified-signal-root');
    await root.locator('[data-use-symbol="BULL"]').waitFor();
    check(await page.locator('#page-pane-unified-signal-engine').isVisible(),'owner deep link opens the engine');
    await root.locator('[data-use-symbol="BULL"]').click();
    if(width<700)check(await root.locator('[data-use-search]').evaluate(el=>el.getBoundingClientRect().width)>200,'phone search remains usable');
    await root.locator('[data-use-view="decision"]').click();
    await root.locator('.use-decision-head').scrollIntoViewIfNeeded();
    check((await root.innerText()).includes('Entry qualified at build'),'fresh policy-qualified setup is labeled at-build');
    check((await root.innerText()).includes('What challenges it'),'counterevidence is visible');
    await page.screenshot({path:resolve(output,`decision-${width}-${theme}.png`),fullPage:false});
    await root.locator('[data-use-view="prices"]').click();
    check(await root.locator('.use-view-tabs [data-use-view="prices"]').evaluate(el=>el===document.activeElement),'focused assessment tab retains keyboard focus');
    check((await root.innerText()).includes('regularMarketPrice'),'selected upstream price field is visible');
    check((await root.innerText()).includes('Independent fair value is not estimated'),'missing independent valuation stays explicit');
    await root.locator('.use-view-tabs [data-use-view="vehicles"]').click();
    await root.locator('.use-view-tabs').scrollIntoViewIfNeeded();
    check((await root.innerText()).includes('The denominators differ'),'stock and option risk bases are distinguished');
    await page.screenshot({path:resolve(output,`vehicles-${width}-${theme}.png`),fullPage:false});
    await root.locator('.use-view-tabs [data-use-view="investment"]').click();
    await root.locator('.use-view-tabs').scrollIntoViewIfNeeded();
    check((await root.locator('[data-use-investment-result]').innerText()).includes('Below the scenario value range'),'investment perspective compares the recorded price with modeled values');
    check((await root.locator('.use-view').innerText()).includes('not probability intervals'),'financial scenario ranges retain their meaning');
    await root.locator('[data-use-investment-field="exitMultiple"]').fill('5');
    check(await root.locator('[data-use-investment-field="exitMultiple"]').evaluate(el=>el===document.activeElement),'live calculations preserve the focused assumption input');
    await root.locator('[data-use-view="trading"]').click();
    check(await root.locator('.use-view-tabs [data-use-view="trading"]').getAttribute('aria-pressed')==='true','the first tab click works directly after editing an assumption');
    await root.locator('[data-use-view="investment"]').click();
    await root.locator('[data-use-investment-field="exitMultiple"]').fill('6');
    await root.locator('[data-use-investment-reset]').click();
    check(await root.locator('[data-use-investment-field="exitMultiple"]').inputValue()==='20','the first Reset click works directly after editing an assumption');
    await root.locator('[data-use-investment-field="exitMultiple"]').fill('5');
    await root.locator('[data-use-investment-field="exitMultiple"]').blur();
    check((await root.locator('[data-use-investment-result]').innerText()).includes('Above the scenario value range'),'a changed valuation assumption updates the investment conclusion');
    check((await root.locator('.use-decision-head').innerText()).includes('Entry qualified at build'),'temporary investment scenarios do not change existing execution policy');
    await root.locator('[data-use-investment-reset]').click();
    check(await root.locator('[data-use-investment-field="exitMultiple"]').inputValue()==='20','reset restores the saved source assumptions');
    await root.locator('[data-use-investment-field="growthPct"]').fill('');
    await root.locator('[data-use-investment-field="growthPct"]').blur();
    check((await root.locator('[data-use-investment-result]').innerText()).includes('Review assumptions'),'blank financial assumptions withhold scenario prices');
    await root.locator('[data-use-investment-reset]').click();
    await root.locator('.use-view-tabs').scrollIntoViewIfNeeded();
    await page.screenshot({path:resolve(output,`investment-${width}-${theme}.png`),fullPage:false});
    await root.locator('[data-use-view="trading"]').click();
    check((await root.locator('.use-view').innerText()).includes('Snapped-streak reversal'),'trading perspective exposes the setup from completed prices');
    check((await root.locator('.use-view').innerText()).includes('five-session IV falling'),'below-average falling IV is not described as recovering');
    check((await root.locator('.use-view').innerText()).includes('not executable trade returns'),'historical stock outcomes are not sold as trading performance');
    await root.locator('[data-use-symbol="WAIT"]').click();
    check((await root.locator('.use-view').innerText()).includes('Research only'),'independent setup cannot override an owner wait');
    await root.locator('[data-use-symbol="BULL"]').click();
    await root.locator('.use-view-tabs').scrollIntoViewIfNeeded();
    await page.screenshot({path:resolve(output,`trading-${width}-${theme}.png`),fullPage:false});
    check(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),'new perspective views have no page overflow');
    await root.locator('[data-use-view="vehicles"]').click();
    await root.locator('[data-use-symbol="BEAR"]').click();
    check((await root.innerText()).includes('Short shares not assessed'),'bearish research does not assume borrow');
    check((await root.innerText()).includes('Entry credit per share')&&(await root.innerText()).includes('Short call'),'credit and spread legs are explicit');
    await root.locator('[data-use-view="evidence"]').click();
    await root.locator('[data-use-symbol="BULL"]').click();
    await root.locator('details').filter({hasText:'Measurements and related context'}).locator('summary').click();
    check((await root.innerText()).includes('not a stock forecast'),'raw IV measurement retains its meaning');
    check((await root.innerText()).includes('2026-10-23 · date only'),'day-level evidence is not shifted into the prior US date');
    await root.locator('[data-use-search]').fill('WAIT');
    check(await root.locator('[data-use-symbol]').count()===1,'ticker search filters the research list');
    await root.locator('[data-use-search]').fill('NORESULT');
    check((await root.innerText()).includes('No matching research'),'empty search has a useful state');
    await root.locator('[data-use-search]').fill('');
    await root.locator('[data-use-filter]').selectOption('avoid');
    check(await root.locator('[data-use-symbol="AVOID"]').count()===1,'AI-rejected research remains in the avoid filter');
    await root.locator('[data-use-filter]').selectOption('all');
    await root.locator('[data-use-symbol="BEAR"]').click();
    await root.locator('[data-use-view="prices"]').click();
    await page.reload();await root.locator('.use-view').waitFor();
    check((await root.locator('.use-decision-head').innerText()).includes('BEAR'),'selected ticker persists');
    check((await root.innerText()).includes('Observed stock price'),'focused view persists');
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
    check(!overflow,'page has no horizontal overflow after resize');
    const saved=await page.evaluate(()=>localStorage.getItem('stonks-unified-view'));
    check(!saved.includes('evidence')&&!saved.includes('snapshotId'),'only preferences persist in browser storage');
  }
  const root=page.locator('#unified-signal-root');
  await root.locator('[data-use-symbol="BULL"]').click();
  preview.setScenario('hang');await root.locator('[data-use-refresh]').click();
  await page.clock.fastForward(16000);
  await root.locator('[role="alert"]').waitFor({timeout:3000});
  check((await root.innerText()).includes('timed out'),'a stalled snapshot request has a readable timeout');
  check(await root.locator('[data-use-refresh]').isEnabled(),'timed-out refresh can be retried');
  check(await root.locator('[data-use-refresh]').evaluate(el=>el===document.activeElement),'refresh restores keyboard focus after a timeout');
  check(!(await root.locator('.use-decision-head').innerText()).includes('Entry qualified at build'),'a timeout cannot preserve an entry badge');
  await root.locator('[data-use-view="decision"]').click();
  check((await root.locator('.use-view').innerText()).includes('Refresh the published snapshot before considering an entry'),'stale or failed-refresh blocks remain visible inside the ticker decision');
  preview.setScenario('error');await root.locator('[data-use-refresh]').click();
  await root.locator('[role="alert"]').waitFor();
  check((await root.innerText()).includes('Previous snapshot is reference only'),'refresh failure demotes old snapshot');
  check(!(await root.locator('.use-decision-head').innerText()).includes('Entry qualified at build'),'failed refresh cannot retain entry eligibility');
  preview.setScenario('revoked');await root.locator('[data-use-refresh]').click();
  await root.locator('.use-empty').waitFor();
  check(!(await root.innerText()).includes('BULL'),'revoked access clears loaded private decisions');
  for(const scenario of ['missing','malformed','empty','stale']){
    preview.setScenario(scenario);await page.reload();
    await root.locator('[data-use-refresh]').waitFor();
    check(!(await root.innerText()).includes('Entry qualified at build'),scenario+' cannot present an eligible entry');
  }
  preview.setScenario('owner');await page.reload();await root.locator('[data-use-symbol="BULL"]').waitFor();
  await root.locator('[data-use-symbol="BULL"]').click();
  await root.locator('[data-use-view="evidence"]').click();
  const contextDetails=root.locator('[data-use-details="context"]');
  await contextDetails.locator('summary').click();
  await page.clock.fastForward(3600001);
  check(!(await root.locator('.use-decision-head').innerText()).includes('Entry qualified at build'),'visible view loses entry eligibility as its quote expires');
  check(await contextDetails.evaluate(el=>el.open),'evidence stays expanded through automatic expiry');
  check(await contextDetails.locator('summary').evaluate(el=>el===document.activeElement),'automatic expiry retains keyboard focus');
  for(const scenario of ['anonymous','tp-only','tr-only','disabled']){
    preview.setScenario(scenario);const count=preview.requests;
    await page.reload();await page.waitForFunction(()=>!!document.querySelector('#page-pane-home')&&!document.querySelector('#page-pane-unified-signal-engine'));
    check(await page.locator('[data-page-tab="unified-signal-engine"]').count()===0,'owner navigation removed for '+scenario);
    check(preview.requests===count,'no decision request for '+scenario);
  }
  check(errors.length===0,'browser reports no runtime errors: '+errors.join('; '));
  console.log(`Unified Signal Engine browser: ${checks} checks passed. Screenshots: ${output}`);
}finally{await browser.close();await new Promise(resolve=>preview.server.close(resolve));}
