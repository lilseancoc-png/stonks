import assert from "node:assert/strict";
import { auditTranscriptLog } from "./audit-transcript-output.mjs";

const response = "[ai] AXP earnings-call gemini-3.6-flash in=12836 cached=0 out=15807 thought=559";
const failed = auditTranscriptLog(`${response}\n[calls] AXP summary failed: response hit the maxOutputTokens cap\nearnings-calls: 73/74 names covered, 0 new summaries`);
assert.equal(failed.acceptedSummaries,0);
assert.equal(failed.recordedModelResponses,1);
assert.equal(failed.ledgerUsdPerAcceptedSummary,null);
assert.ok(Math.abs(failed.ledgerEstimatedUsd-.141999)<1e-9);
assert.equal(failed.summaryFailures[0].symbol,"AXP");
assert.equal(auditTranscriptLog(response).acceptedSummaries,null,"missing final count must not become zero");
const accepted = auditTranscriptLog(`${response}\nearnings-calls: 74/74 names covered, 1 new summary`);
assert.equal(accepted.ledgerUsdPerAcceptedSummary,accepted.ledgerEstimatedUsd);
const unknown = auditTranscriptLog("[ai] AXP earnings-call unknown-model in=10 cached=0 out=20\nearnings-calls: 74/74 names covered, 1 new summary");
assert.equal(unknown.ledgerEstimatedUsd,null,"unknown model cost must not become zero");
assert.equal(unknown.ledgerUsdPerAcceptedSummary,null);
assert.deepEqual(unknown.unpricedModels,["unknown-model"]);
const missingUsage = auditTranscriptLog("[ai] AXP earnings-call gemini-3.6-flash in=? cached=0 out=?\nearnings-calls: 74/74 names covered, 1 new summary");
assert.equal(missingUsage.recordedModelResponses,1);
assert.equal(missingUsage.ledgerEstimatedUsd,null,"missing usage must not silently become free");
assert.deepEqual(missingUsage.incompleteUsageSymbols,["AXP"]);
assert.deepEqual(missingUsage.unpricedModels,[],"missing usage is distinct from unknown model pricing");
const lostResponses = auditTranscriptLog("earnings-calls: 74/74 names covered, 1 new summary");
assert.equal(lostResponses.missingResponseUsage,true);
assert.equal(lostResponses.ledgerEstimatedUsd,null,"published summaries with missing response rows must not appear free");
assert.equal(lostResponses.ledgerUsdPerAcceptedSummary,null);
const partiallyLost = auditTranscriptLog(`${response}\nearnings-calls: 74/74 names covered, 2 new summaries`);
assert.equal(partiallyLost.ledgerEstimatedUsd,null);
assert.throws(()=>auditTranscriptLog("earnings-calls: 1/2 names covered, 0 new summaries\nearnings-calls: 2/2 names covered, 1 new summary"),/multiple transcript runs/);
console.log("transcript output audit: failed, accepted, missing and unpriced results remain distinct");
